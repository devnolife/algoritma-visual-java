/**
 * Skenario uji fidelitas koleksi. Satu sumber untuk dua sisi:
 * - scripts/fixture-koleksi.ts membangkitkan program Java darinya, menjalankannya di JDK 21,
 *   lalu menyimpan hasil per langkah di tests/engine/koleksi/fixture/*.json;
 * - tests/engine/koleksi/skenario.test.ts memutar ulang skenario yang sama pada model (putar.ts).
 *
 * Langkah = tuple `[op, ...argumen]`. Awalan `d.` pada op menargetkan variabel kedua (`d`), awalan `w.` view map
 * (`lihatKunci`/`lihatNilai`/`lihatEntri`), selainnya `c`. `e` menampung Map.Entry (`itNextEntri`, atau
 * `eAmbil` = hasil langkah bersarang, mis. `['eAmbil', 'd.firstEntry']`).
 * Argumen bertipe menurut op: int (indeks/kapasitas), elemen (angka → Integer, K, atau H, teks → String,
 * null, '!orang' → objek non-Comparable), variabel ('@c', '@d', '@w', '@e', null), pembanding ('#log',
 * '#terbalik', '#ubah', null), dan '#NaN' (Float.NaN) untuk load factor.
 */
export type Arg = number | string | null
export type Langkah = readonly [string, ...Arg[]]
export type TipeElemen = 'Integer' | 'String' | 'K' | 'H'

export interface Skenario {
  nama: string
  /** Nama berkas fixture (tanpa .json). */
  berkas: string
  /** Tipe elemen untuk literal angka; 'K' = kunci pencatat (equals/hashCode/compareTo/toString tercatat). */
  elemen?: TipeElemen
  langkah: readonly Langkah[]
}

