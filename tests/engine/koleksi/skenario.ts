/** Operasi acak offer/poll/remove(Object) yang deterministik. */
function pqAcak(benih: number, jumlah: number): Langkah[] {
  const r = buatAcak(benih)
  const hasil: Langkah[] = []
  for (let i = 0; i < jumlah; i++) {
    const p = r() % 10
    if (p < 6) hasil.push(['offer', r() % 50])
    else if (p < 9) hasil.push(['poll'])
    else hasil.push(['removeObjek', r() % 50])
  }
  return hasil
}

