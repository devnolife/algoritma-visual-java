/** `n` bilangan unik acak di [0, batas) dalam urutan acak. */
function acakUnik(benih: number, n: number, batas: number): number[] {
  const r = buatAcak(benih)
  const hasil: number[] = []
  while (hasil.length < n) {
    const x = r() % batas
    if (!hasil.includes(x)) hasil.push(x)
  }
  return hasil
}

