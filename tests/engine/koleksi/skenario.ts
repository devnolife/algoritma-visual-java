/** LCG bersama (juga dipakai sisi Java untuk pembanding 'kacau'): 0..32767. */
export function buatAcak(benih: number): () => number {
  let x = benih | 0
  return () => {
    x = (Math.imul(x, 1103515245) + 12345) | 0
    return (x >>> 16) & 0x7fff
  }
}

const rentang = (a: number, b: number) => Array.from({ length: b - a }, (_, i) => a + i)
const ulang = (op: string, nilai: Arg[]): Langkah[] => nilai.map((v) => [op, v] as const)

export const SKENARIO: Skenario[] = []
const tambah = (...s: Skenario[]) => SKENARIO.push(...s)

